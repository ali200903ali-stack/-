-- NineSoft v1 — MySQL 8 / MariaDB 10.5+, UTF8MB4; create an empty database first.
SET NAMES utf8mb4;
CREATE TABLE IF NOT EXISTS users (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(120) NOT NULL,
 email VARCHAR(190) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL,
 role ENUM('admin','accountant','cashier','viewer') NOT NULL DEFAULT 'viewer',
 branch_id BIGINT UNSIGNED NULL,
 active TINYINT(1) NOT NULL DEFAULT 1,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS branches (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(140) NOT NULL,
 active TINYINT(1) NOT NULL DEFAULT 1
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS customers (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(190) NOT NULL,
 phone VARCHAR(50) DEFAULT '',
 address VARCHAR(255) DEFAULT '',
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS suppliers (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(190) NOT NULL,
 phone VARCHAR(50) DEFAULT '',
 address VARCHAR(255) DEFAULT '',
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS accounts (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 code VARCHAR(30) NOT NULL UNIQUE,
 name VARCHAR(160) NOT NULL,
 type ENUM('asset','liability','equity','revenue','expense') NOT NULL,
 is_system TINYINT(1) NOT NULL DEFAULT 0,
 active TINYINT(1) NOT NULL DEFAULT 1
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS products (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 sku VARCHAR(100) NOT NULL UNIQUE,
 name VARCHAR(190) NOT NULL,
 category VARCHAR(100) DEFAULT '',
 unit VARCHAR(50) NOT NULL DEFAULT 'حبة',
 price DECIMAL(18,2) NOT NULL DEFAULT 0,
 cost DECIMAL(18,2) NOT NULL DEFAULT 0,
 stock DECIMAL(18,3) NOT NULL DEFAULT 0,
 min_stock DECIMAL(18,3) NOT NULL DEFAULT 0,
 track_stock TINYINT(1) NOT NULL DEFAULT 1,
 active TINYINT(1) NOT NULL DEFAULT 1,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS invoices (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 number VARCHAR(50) NOT NULL UNIQUE,
 kind ENUM('sale','purchase','return') NOT NULL,
 status ENUM('draft','posted') NOT NULL DEFAULT 'draft',
 branch_id BIGINT UNSIGNED NOT NULL,
 customer_id BIGINT UNSIGNED NULL,
 supplier_id BIGINT UNSIGNED NULL,
 reference_id BIGINT UNSIGNED NULL,
 date DATE NOT NULL,
 payment ENUM('cash','bank','credit') NOT NULL DEFAULT 'cash',
 paid DECIMAL(18,2) DEFAULT NULL,
 discount DECIMAL(18,2) NOT NULL DEFAULT 0,
 discount_type ENUM('amount','percent') NOT NULL DEFAULT 'amount',
 tax_rate DECIMAL(7,3) NOT NULL DEFAULT 0,
 subtotal DECIMAL(18,2) NOT NULL DEFAULT 0,
 net DECIMAL(18,2) NOT NULL DEFAULT 0,
 tax DECIMAL(18,2) NOT NULL DEFAULT 0,
 total DECIMAL(18,2) NOT NULL DEFAULT 0,
 note TEXT NULL,
 revision INT UNSIGNED NOT NULL DEFAULT 1,
 created_by BIGINT UNSIGNED NOT NULL,
 posted_at TIMESTAMP NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 INDEX idx_invoice_date(kind,status,date),
 INDEX idx_invoice_party(customer_id,supplier_id),
 INDEX idx_invoice_branch(branch_id,date)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS invoice_lines (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 invoice_id BIGINT UNSIGNED NOT NULL,
 product_id BIGINT UNSIGNED NOT NULL,
 qty DECIMAL(18,3) NOT NULL,
 price DECIMAL(18,2) NOT NULL,
 cost_at_post DECIMAL(18,2) NULL,
 INDEX idx_line_invoice(invoice_id),
 INDEX idx_line_product(product_id),
 FOREIGN KEY(invoice_id) REFERENCES invoices(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS journal_entries (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 number VARCHAR(60) NOT NULL UNIQUE,
 date DATE NOT NULL,
 description VARCHAR(500) NOT NULL,
 branch_id BIGINT UNSIGNED NOT NULL,
 source ENUM('manual','sale','purchase','return','voucher','opening') NOT NULL DEFAULT 'manual',
 source_id BIGINT UNSIGNED NULL,
 created_by BIGINT UNSIGNED NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE KEY uniq_source(source,source_id),
 INDEX idx_journal_date(date,branch_id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS journal_lines (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 journal_id BIGINT UNSIGNED NOT NULL,
 account_id BIGINT UNSIGNED NOT NULL,
 debit DECIMAL(18,2) NOT NULL DEFAULT 0,
 credit DECIMAL(18,2) NOT NULL DEFAULT 0,
 party_type ENUM('customer','supplier') NULL,
 party_id BIGINT UNSIGNED NULL,
 INDEX idx_jline_account(account_id),
 INDEX idx_jline_party(party_type,party_id),
 FOREIGN KEY(journal_id) REFERENCES journal_entries(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS vouchers (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 number VARCHAR(60) NOT NULL UNIQUE,
 kind ENUM('receipt','payment') NOT NULL,
 date DATE NOT NULL,
 party_id BIGINT UNSIGNED NOT NULL,
 account_id BIGINT UNSIGNED NOT NULL,
 amount DECIMAL(18,2) NOT NULL,
 description VARCHAR(500) NOT NULL,
 branch_id BIGINT UNSIGNED NOT NULL,
 created_by BIGINT UNSIGNED NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 INDEX idx_voucher_date(date,branch_id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS sequences (
 name VARCHAR(20) PRIMARY KEY,
 current_value BIGINT UNSIGNED NOT NULL DEFAULT 0
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS settings (
 name VARCHAR(100) PRIMARY KEY,
 value TEXT NOT NULL
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS audit_logs (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 user_id BIGINT UNSIGNED NOT NULL,
 action VARCHAR(100) NOT NULL,
 entity VARCHAR(50) NOT NULL,
 entity_id VARCHAR(80) NOT NULL,
 ip VARCHAR(50) NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 INDEX idx_audit_time(created_at)
) ENGINE=InnoDB;
